    'Trading quotation currency; not the same as underlying economic FX exposure. A USD-quoted Japan ETF already includes JPY/USD effects in its USD return.';

CREATE TABLE IF NOT EXISTS public.series_definitions (
    series_id text PRIMARY KEY,
    source_id text NOT NULL REFERENCES public.data_sources(source_id),
    source_series_code text NOT NULL,
    label text NOT NULL,
    series_kind text NOT NULL,
    unit text NOT NULL,
    frequency text NOT NULL,
    reference_currency text,
    exposure_id text REFERENCES public.asset_exposures(exposure_id),
    instrument_id text REFERENCES public.instruments(instrument_id),
    return_basis text NOT NULL DEFAULT 'not_applicable',
    publication_timezone text,
    attributes jsonb NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE (series_id, source_id),
    CHECK (return_basis IN ('total_return', 'price_only', 'yield', 'level', 'unknown', 'not_applicable')),
    CHECK (jsonb_typeof(attributes) = 'object')
);

CREATE TABLE IF NOT EXISTS public.raw_ingestion_runs (
    ingestion_run_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id text NOT NULL REFERENCES public.data_sources(source_id),
    started_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at timestamptz,
    status text NOT NULL DEFAULT 'running',
    request_fingerprint text,
    artifact_uri text,
    artifact_sha256 text,
    records_received bigint NOT NULL DEFAULT 0,
    records_inserted bigint NOT NULL DEFAULT 0,
    error_summary text,
    attributes jsonb NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE (ingestion_run_id, source_id),
    CHECK (status IN ('running', 'complete', 'partial', 'failed')),
    CHECK (completed_at IS NULL OR completed_at >= started_at),
    CHECK (records_received >= 0 AND records_inserted >= 0),
    CHECK (artifact_sha256 IS NULL OR artifact_sha256 ~ '^[0-9a-f]{64}$'),
    CHECK (jsonb_typeof(attributes) = 'object')

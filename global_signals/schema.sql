COMMENT ON COLUMN public.raw_ingestion_runs.request_fingerprint IS
    'Sanitized request identifier or digest; never store API keys, proxy credentials, or secret-bearing URLs.';

CREATE TABLE IF NOT EXISTS public.observations (
    observation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id text NOT NULL,
    source_id text NOT NULL,
    ingestion_run_id bigint NOT NULL,
    observed_period_start date NOT NULL,
    observed_period_end date NOT NULL,
    value numeric,
    raw_value text,
    quality_status text NOT NULL DEFAULT 'observed',
    known_available_at timestamptz,
    availability_basis text NOT NULL DEFAULT 'first_seen',
    first_seen_at timestamptz NOT NULL,
    retrieved_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    source_vintage_at timestamptz,
    revision_key text NOT NULL,
    attributes jsonb NOT NULL DEFAULT '{}'::jsonb,
    FOREIGN KEY (series_id, source_id)
        REFERENCES public.series_definitions(series_id, source_id),
    FOREIGN KEY (ingestion_run_id, source_id)
        REFERENCES public.raw_ingestion_runs(ingestion_run_id, source_id),
    UNIQUE (series_id, observed_period_start, observed_period_end, revision_key),
    CHECK (observed_period_end >= observed_period_start),
    CHECK (first_seen_at <= retrieved_at),
    CHECK (known_available_at IS NULL OR known_available_at <= retrieved_at),
    CHECK (availability_basis IN ('source_published', 'first_seen', 'unknown')),
    CHECK (availability_basis <> 'source_published' OR known_available_at IS NOT NULL),
    CHECK (quality_status IN ('observed', 'missing', 'invalid')),
    CHECK (quality_status <> 'observed' OR value IS NOT NULL),
    CHECK (length(trim(revision_key)) > 0),
    CHECK (jsonb_typeof(attributes) = 'object')
);

COMMENT ON COLUMN public.observations.known_available_at IS
    'Verified public availability time of this exact version, not the economic observation date. Leave NULL when unknown.';
COMMENT ON COLUMN public.observations.first_seen_at IS
    'When this project first captured this version. Historical downloads do not establish historical availability.';
COMMENT ON COLUMN public.observations.source_vintage_at IS
    'Source-declared revision/vintage timestamp; distinct from observation period and retrieval timestamp.';
COMMENT ON COLUMN public.observations.revision_key IS
    'Stable source revision identifier or canonical content digest. New revisions append rows; they do not overwrite old values.';

CREATE OR REPLACE FUNCTION public.global_signals_guard_observations()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'global_signals observations are append-only; insert a new revision instead';
END;
$$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'public.observations'::regclass
          AND tgname = 'global_signals_observations_no_mutation'
          AND NOT tgisinternal
    ) THEN
        CREATE TRIGGER global_signals_observations_no_mutation
        BEFORE UPDATE OR DELETE ON public.observations
        FOR EACH ROW EXECUTE FUNCTION public.global_signals_guard_observations();
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'public.observations'::regclass
          AND tgname = 'global_signals_observations_no_truncate'
          AND NOT tgisinternal
    ) THEN
        CREATE TRIGGER global_signals_observations_no_truncate
        BEFORE TRUNCATE ON public.observations
        FOR EACH STATEMENT EXECUTE FUNCTION public.global_signals_guard_observations();
    END IF;
END;
$$;

CREATE OR REPLACE VIEW public.observation_availability AS
SELECT o.*,
       CASE o.availability_basis
           WHEN 'source_published' THEN o.known_available_at
           WHEN 'first_seen' THEN o.first_seen_at
           ELSE NULL
       END AS effective_available_at
FROM public.observations o;


-- Keep unhedged and KRW-hedged forecasts separate. These display rows do not
-- insert placeholder predictions. A newer invalid forecast does not revive an
-- older green forecast. Context-only and KRW-reference exposures have no separate
-- KRW hedge variant. Portfolio execution is outside this research schema.
CREATE OR REPLACE VIEW public.exposure_signal_variants AS
SELECT e.exposure_id, e.label, e.asset_class, e.country_code,
       e.reference_currency, e.monitor_only, e.attributes,
       p.prediction_id, p.instrument_id, p.prediction_as_of, p.valid_until,
       COALESCE(p.forecast_horizon, '1_calendar_month') AS forecast_horizon,
       COALESCE(p.reporting_currency, 'KRW') AS reporting_currency,
       variant.currency_treatment, p.cash_benchmark_series_id,
       p.probability_outperform_cash, p.excess_return_p10,
       p.excess_return_p50, p.excess_return_p90,
       p.expected_shortfall_95, p.risk_adjusted_score, p.confidence_score,
       p.transaction_cost_fraction, p.hedge_carry_fraction,
       p.cost_assumptions, p.risk_policy,
       m.validation_status AS model_validation_status,
       f.quality_status AS feature_quality_status,
       CASE WHEN guard.gray_reason IS NOT NULL THEN 'gray'
            ELSE p.signal_color END AS signal_color,
       guard.gray_reason,
       COALESCE(p.reason_codes, ARRAY[]::text[]) AS reason_codes,
       p.hedge_quote_id, p.hedge_cashflow_method,
       q.source_quality AS hedge_quote_quality,
       q.pricing_basis AS hedge_pricing_basis,
       q.foreign_currency AS hedge_quote_currency,
       q.valid_until AS hedge_quote_valid_until
FROM public.asset_exposures e
CROSS JOIN (VALUES ('unhedged'::text), ('krw_hedged'::text))
    AS variant(currency_treatment)
LEFT JOIN LATERAL (
    SELECT s.* FROM public.signal_predictions s
    WHERE s.exposure_id = e.exposure_id
      AND s.currency_treatment = variant.currency_treatment
      AND s.prediction_as_of <= CURRENT_TIMESTAMP
      AND s.created_at <= CURRENT_TIMESTAMP
    ORDER BY s.prediction_as_of DESC, s.created_at DESC, s.prediction_id DESC
    LIMIT 1
) p ON true
LEFT JOIN public.model_runs m ON m.model_run_id = p.model_run_id
LEFT JOIN public.feature_snapshots f ON f.feature_snapshot_id = p.feature_snapshot_id
LEFT JOIN public.instruments i ON i.instrument_id = p.instrument_id
LEFT JOIN public.fx_hedge_quotes q ON q.hedge_quote_id = p.hedge_quote_id
CROSS JOIN LATERAL (
    SELECT CASE
        WHEN e.monitor_only THEN 'context_only'
        WHEN p.prediction_id IS NULL THEN 'no_forecast'
        WHEN e.attributes->>'data_status' IS DISTINCT FROM 'verified' THEN 'data_unverified'
        WHEN i.investability_status IS DISTINCT FROM 'eligible' THEN 'instrument_not_verified'
        WHEN i.exposure_id IS DISTINCT FROM e.exposure_id THEN 'instrument_exposure_mismatch'
        WHEN p.valid_until <= CURRENT_TIMESTAMP THEN 'forecast_expired'
        WHEN m.validation_status IS DISTINCT FROM 'validated' THEN 'model_not_validated'
        WHEN m.validation_completed_at > p.prediction_as_of THEN 'model_validation_after_cutoff'
        WHEN m.training_data_cutoff > p.prediction_as_of THEN 'model_training_after_cutoff'
        WHEN f.as_of > p.prediction_as_of THEN 'features_after_cutoff'
        WHEN f.quality_status IS DISTINCT FROM 'ok' THEN 'features_not_ready'
        WHEN p.forecast_status <> 'ready' THEN p.forecast_status
        WHEN variant.currency_treatment = 'krw_hedged'
             AND p.hedge_cashflow_method IS NULL THEN 'hedge_cashflow_unknown'
        WHEN variant.currency_treatment = 'krw_hedged'
             AND p.hedge_cashflow_method = 'product_embedded' THEN 'embedded_hedge_not_verified'
        WHEN variant.currency_treatment = 'krw_hedged'
             AND q.hedge_quote_id IS NULL THEN 'hedge_quote_missing'
        WHEN variant.currency_treatment = 'krw_hedged'
             AND (q.source_quality <> 'executable' OR q.pricing_basis <> 'observed_forward')
             THEN 'hedge_quote_not_executable'
        WHEN variant.currency_treatment = 'krw_hedged'
             AND q.execution_access <> 'verified' THEN 'hedge_execution_access_unverified'
        WHEN variant.currency_treatment = 'krw_hedged'
             AND (q.quoted_at > p.prediction_as_of OR q.available_at > p.prediction_as_of)
             THEN 'hedge_quote_after_cutoff'
        WHEN variant.currency_treatment = 'krw_hedged'
             AND q.valid_until <= p.prediction_as_of THEN 'hedge_quote_expired_at_forecast'
        WHEN variant.currency_treatment = 'krw_hedged'
             AND q.foreign_currency IS DISTINCT FROM i.quote_currency
             THEN 'hedge_quote_currency_mismatch'
        WHEN variant.currency_treatment = 'krw_hedged'
             AND (q.value_date <> p.target_period_start OR q.maturity_date <> p.target_period_end)
             THEN 'hedge_quote_tenor_mismatch'
        WHEN variant.currency_treatment = 'krw_hedged'
             AND q.explicit_cost_fraction IS NULL THEN 'hedge_cost_unknown'
        WHEN p.signal_color = 'gray' THEN 'model_abstained'
        ELSE NULL
    END AS gray_reason
) guard
WHERE variant.currency_treatment = 'unhedged'
   OR (NOT e.monitor_only AND e.reference_currency IS DISTINCT FROM 'KRW');


CREATE TABLE IF NOT EXISTS public.instruments (
    instrument_id text PRIMARY KEY,
    exposure_id text NOT NULL REFERENCES public.asset_exposures(exposure_id),
    label text NOT NULL,
    ticker text,
    venue text,
    quote_currency text NOT NULL,
    economic_currency_exposures jsonb NOT NULL DEFAULT '{}'::jsonb,
    hedge_type text NOT NULL DEFAULT 'unknown',
    hedge_target_currency text,
    hedge_ratio numeric,
    investability_status text NOT NULL DEFAULT 'unknown',
    attributes jsonb NOT NULL DEFAULT '{}'::jsonb,
    CHECK (hedge_type IN ('unhedged', 'currency_hedged', 'partial', 'unknown')),

CREATE TABLE IF NOT EXISTS public.signal_predictions (
    prediction_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exposure_id text NOT NULL REFERENCES public.asset_exposures(exposure_id),
    instrument_id text REFERENCES public.instruments(instrument_id),
    feature_snapshot_id bigint NOT NULL,
    model_run_id bigint NOT NULL REFERENCES public.model_runs(model_run_id),
    prediction_as_of timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    valid_until timestamptz NOT NULL,
    target_period_start date NOT NULL,
    target_period_end date NOT NULL,
    forecast_horizon text NOT NULL DEFAULT '1_calendar_month',
    reporting_currency text NOT NULL DEFAULT 'KRW',
    target_definition text NOT NULL DEFAULT 'krw_net_excess_over_cash',
    currency_treatment text NOT NULL,
    cash_benchmark_series_id text NOT NULL REFERENCES public.series_definitions(series_id),
    probability_outperform_cash numeric,
    excess_return_p10 numeric,
    excess_return_p50 numeric,
    excess_return_p90 numeric,
    expected_shortfall_95 numeric,
    risk_adjusted_score numeric,
    confidence_score numeric,
    transaction_cost_fraction numeric NOT NULL,
    hedge_carry_fraction numeric,
    cost_assumptions jsonb NOT NULL,
    hedge_assumptions jsonb NOT NULL DEFAULT '{}'::jsonb,
    risk_policy jsonb NOT NULL,
    forecast_status text NOT NULL DEFAULT 'unknown',
    signal_color text NOT NULL DEFAULT 'gray',
    reason_codes text[] NOT NULL DEFAULT ARRAY[]::text[],
    FOREIGN KEY (feature_snapshot_id, exposure_id)
        REFERENCES public.feature_snapshots(feature_snapshot_id, exposure_id),
    CHECK (valid_until > prediction_as_of),
    CHECK (forecast_horizon = '1_calendar_month'),
    CHECK (target_period_end = (target_period_start + interval '1 month')::date),
    CHECK (reporting_currency = 'KRW'),
    CHECK (target_definition = 'krw_net_excess_over_cash'),
    CHECK (currency_treatment IN ('unhedged', 'krw_hedged')),
    CHECK (probability_outperform_cash IS NULL OR probability_outperform_cash BETWEEN 0 AND 1),
    CHECK (confidence_score IS NULL OR confidence_score BETWEEN 0 AND 1),
    CHECK (excess_return_p10 IS NULL OR excess_return_p50 IS NULL OR excess_return_p10 <= excess_return_p50),
    CHECK (excess_return_p50 IS NULL OR excess_return_p90 IS NULL OR excess_return_p50 <= excess_return_p90),
    CHECK (transaction_cost_fraction >= 0),
    CHECK (currency_treatment <> 'krw_hedged' OR hedge_carry_fraction IS NOT NULL),
    CHECK (forecast_status IN ('ready', 'unknown', 'insufficient_data', 'unvalidated')),
    CHECK (signal_color IN ('green', 'yellow', 'red', 'gray')),
    CHECK (signal_color = 'gray' OR (
        forecast_status = 'ready'
        AND probability_outperform_cash IS NOT NULL
        AND excess_return_p10 IS NOT NULL
        AND excess_return_p50 IS NOT NULL
        AND excess_return_p90 IS NOT NULL
    )),
    CHECK (jsonb_typeof(cost_assumptions) = 'object'),
    CHECK (jsonb_typeof(hedge_assumptions) = 'object'),
    CHECK (jsonb_typeof(risk_policy) = 'object')
);

COMMENT ON COLUMN public.signal_predictions.excess_return_p50 IS
    'Median of KRW total return minus matching-horizon KRW cash return, net of disclosed costs and hedging carry. This is not a raw local-currency price forecast.';
COMMENT ON COLUMN public.signal_predictions.hedge_carry_fraction IS
    'Signed contribution of currency hedge carry/roll to return; positive means a benefit. Unknown hedging economics must not be represented as zero.';
COMMENT ON COLUMN public.signal_predictions.confidence_score IS
    'Optional separately defined evidence/quality measure; not a synonym for probability_outperform_cash.';


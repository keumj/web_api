-- Research diagnostics never imply approval of a production forecasting model.
CREATE TABLE IF NOT EXISTS public.exposure_series_bindings (
    exposure_id text NOT NULL REFERENCES public.asset_exposures(exposure_id),
    series_id text NOT NULL REFERENCES public.series_definitions(series_id),
    analysis_mode text NOT NULL CHECK(analysis_mode IN ('forecast','fx','context')),
    coverage_note text NOT NULL,
    PRIMARY KEY(exposure_id,series_id)
);
CREATE TABLE IF NOT EXISTS public.research_refresh_runs (
    run_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at timestamptz,
    mode text NOT NULL CHECK(mode IN ('direct', 'upload-local')),
    status text NOT NULL DEFAULT 'running' CHECK(status IN ('running','complete','partial','failed')),
    details jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE TABLE IF NOT EXISTS public.research_signals (
    research_signal_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id bigint NOT NULL REFERENCES public.research_refresh_runs(run_id),
    exposure_id text NOT NULL REFERENCES public.asset_exposures(exposure_id),
    as_of timestamptz NOT NULL,
    data_date date,
    valid_until timestamptz NOT NULL,
    status text NOT NULL CHECK(status IN ('ready','stale','insufficient','failed')),
    research_color text NOT NULL CHECK(research_color IN ('green','yellow','red','gray')),
    model_version text NOT NULL,
    metrics jsonb NOT NULL,
    validation jsonb NOT NULL,
    reason_codes text[] NOT NULL,
    UNIQUE(run_id, exposure_id),
    CHECK(valid_until > as_of),
    CHECK(status = 'ready' OR research_color = 'gray')
);
CREATE INDEX IF NOT EXISTS research_signals_latest_idx
    ON public.research_signals(exposure_id, as_of DESC, research_signal_id DESC);
CREATE OR REPLACE VIEW public.research_latest_signals AS
SELECT e.exposure_id, e.label, e.asset_class, e.monitor_only,
       r.research_signal_id, r.run_id, r.as_of, r.data_date, r.valid_until,
       CASE WHEN r.valid_until <= CURRENT_TIMESTAMP THEN 'stale' ELSE COALESCE(r.status,'insufficient') END AS status,
       CASE WHEN r.valid_until <= CURRENT_TIMESTAMP THEN 'gray' ELSE COALESCE(r.research_color,'gray') END AS research_color,
       r.model_version, r.metrics, r.validation,
       CASE WHEN r.valid_until <= CURRENT_TIMESTAMP THEN ARRAY['forecast_expired']::text[]
            ELSE COALESCE(r.reason_codes, ARRAY['not_connected']::text[]) END AS reason_codes
FROM public.asset_exposures e
LEFT JOIN LATERAL (
    SELECT s.* FROM public.research_signals s
    WHERE s.exposure_id=e.exposure_id AND s.as_of <= CURRENT_TIMESTAMP
    ORDER BY s.as_of DESC, s.research_signal_id DESC LIMIT 1
) r ON true;
